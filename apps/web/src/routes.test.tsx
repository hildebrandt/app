// @vitest-environment jsdom
import {
  createMemoryHistory,
  createRouter,
  RouterProvider,
} from "@tanstack/react-router";
import { cleanup, render, screen } from "@testing-library/react";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { afterEach, describe, expect, it } from "vite-plus/test";

import { Route } from "./routes/__root";
import { routeTree } from "./routeTree.gen";

import appCss from "./styles/globals.css?url";

const notFoundStyles =
  "body{color:#000;background:#fff;margin:0}.next-error-h1{border-right:1px solid rgba(0,0,0,.3)}@media (prefers-color-scheme:dark){body{color:#fff;background:#000}.next-error-h1{border-right:1px solid rgba(255,255,255,.3)}}";

interface HeadMetadata {
  links: {
    rel: string;
    href: string;
    as?: string;
    type?: string;
    crossOrigin?: string;
    sizes?: string;
  }[];
  meta: {
    charSet?: string;
    name?: string;
    content?: string;
    title?: string;
  }[];
}

const isHeadFunction = (value: unknown): value is () => HeadMetadata =>
  typeof value === "function";

describe("root route", () => {
  afterEach(cleanup);

  it("defines the document metadata", () => {
    if (!isHeadFunction(Route.options.head)) {
      throw new Error("Root route head is unavailable");
    }

    expect(Route.options.head()).toStrictEqual({
      meta: [
        { charSet: "utf-8" },
        { name: "viewport", content: "width=device-width, initial-scale=1" },
        { title: "Create Next App" },
        { name: "description", content: "Generated by create next app" },
      ],
      links: [
        {
          rel: "preload",
          href: "/fonts/InterVariable.woff2",
          as: "font",
          type: "font/woff2",
          crossOrigin: "anonymous",
        },
        {
          rel: "preload",
          href: "/fonts/GeistMonoVariable.woff2",
          as: "font",
          type: "font/woff2",
          crossOrigin: "anonymous",
        },
        { rel: "stylesheet", href: appCss },
        {
          rel: "icon",
          href: "/favicon.ico?favicon.2vob68tjqpejf.ico",
          sizes: "256x256",
          type: "image/x-icon",
        },
      ],
    });
  });

  it("renders the not found page", () => {
    const NotFound = Route.options.notFoundComponent;

    if (!NotFound) {
      throw new Error("Not found component is unavailable");
    }

    const { container } = render(createElement(NotFound));
    const outer = container.querySelector<HTMLDivElement>("div");
    const heading = screen.getByRole("heading", { level: 1 });
    const subheading = screen.getByRole("heading", { level: 2 });
    const style = container.querySelector("style");

    expect(screen.getByText("404")).toBe(heading);
    expect(screen.getByText("This page could not be found.")).toBe(subheading);

    expect({
      heading: {
        display: heading.style.display,
        fontSize: heading.style.fontSize,
        fontWeight: heading.style.fontWeight,
        lineHeight: heading.style.lineHeight,
        margin: heading.style.margin,
        padding: heading.style.padding,
        verticalAlign: heading.style.verticalAlign,
      },
      outer: {
        alignItems: outer?.style.alignItems,
        display: outer?.style.display,
        flexDirection: outer?.style.flexDirection,
        fontFamily: outer?.style.fontFamily,
        height: outer?.style.height,
        justifyContent: outer?.style.justifyContent,
        textAlign: outer?.style.textAlign,
      },
      robots: document.querySelector<HTMLMetaElement>('meta[name="robots"]')
        ?.content,
      style: style?.textContent,
      subheading: {
        display: subheading.parentElement?.style.display,
        fontSize: subheading.style.fontSize,
        fontWeight: subheading.style.fontWeight,
        lineHeight: subheading.style.lineHeight,
        margin: subheading.style.margin,
      },
    }).toStrictEqual({
      heading: {
        display: "inline-block",
        fontSize: "24px",
        fontWeight: "500",
        lineHeight: "49px",
        margin: "0px 20px 0px 0px",
        padding: "0px 23px 0px 0px",
        verticalAlign: "top",
      },
      outer: {
        alignItems: "center",
        display: "flex",
        flexDirection: "column",
        fontFamily:
          "system-ui, Segoe UI, Roboto, Helvetica, Arial, sans-serif, Apple Color Emoji, Segoe UI Emoji",
        height: "100vh",
        justifyContent: "center",
        textAlign: "center",
      },
      robots: "noindex",
      style: notFoundStyles,
      subheading: {
        display: "inline-block",
        fontSize: "14px",
        fontWeight: "400",
        lineHeight: "49px",
        margin: "0px",
      },
    });
  });

  it("renders the full document with the router", async () => {
    const router = createRouter({
      routeTree,
      history: createMemoryHistory({ initialEntries: ["/"] }),
    });

    await router.load();

    const html = renderToStaticMarkup(
      createElement(RouterProvider, { router })
    );

    expect({
      body: html.includes("<body>"),
      description: html.includes(
        '<meta name="description" content="Generated by create next app"/>'
      ),
      document: html.includes('<html lang="en"><head>'),
      home: html.includes("Get started by editing"),
      title: html.includes("<title>Create Next App</title>"),
    }).toStrictEqual({
      body: true,
      description: true,
      document: true,
      home: true,
      title: true,
    });
  });
});
